#!/usr/bin/env node
/**
 * Copies a fixed set of upstream documents into tests/fixtures/ so the test
 * suite never depends on a 65 MB data build having been run.
 *
 * We commit the *upstream* documents rather than normalized records: the tests
 * then exercise the normalizer end to end, and there is one artifact to keep in
 * sync instead of two. Re-run after bumping the pinned commit.
 */
import { copyFileSync, mkdirSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { ensureUpstream, PROJECT_ROOT } from './upstream.js';

/**
 * Chosen to span every elite/weak HP boundary in Monster Core (level -1 and 0,
 * 1, 2-4, 5-19, 20+) and to cover the shapes the normalizer has to get right:
 * inventory vs. strikes, ranged strikes, regeneration, weaknesses, resistances
 * with exceptions and doubleVs, rule-element-only IWR, innate/prepared/focus
 * spellcasting, and both a simple and a complex hazard.
 */
const FIXTURES = [
  ['pathfinder-monster-core', 'goblin-warrior.json', 'level -1; inventory + strikes, reaction'],
  ['pathfinder-monster-core', 'sprite.json', 'level -1; innate spellcasting'],
  ['pathfinder-monster-core-2', 'badger.json', 'level 0; minimal animal'],
  ['pathfinder-monster-core', 'arbiter.json', 'level 1; construct immunities'],
  ['pathfinder-monster-core', 'boggard-warrior.json', 'level 2; HP boundary 2-4'],
  ['pathfinder-monster-core-2', 'amphisbaena.json', 'level 4; HP boundary 2-4 upper'],
  ['pathfinder-monster-core', 'forest-troll.json', 'level 5; regeneration + weaknesses'],
  ['pathfinder-monster-core', 'ghost-mage.json', 'level 10; resistances with exceptions, fly, incorporeal'],
  ['pathfinder-monster-core', 'lich.json', 'level 12; prepared spellcasting, rule-element resistance, rare'],
  ['pathfinder-monster-core-2', 'cinder-dragon-ancient.json', 'level 19; breath weapon, HP boundary 5-19 upper'],
  ['pathfinder-monster-core-2', 'baomal.json', 'level 20; HP boundary 20+'],
  ['pathfinder-monster-core', 'grim-reaper.json', 'level 21; unique'],
  ['pathfinder-monster-core-2', 'green-man.json', 'level 24; top of range'],
  ['hazards', 'hidden-pit.json', 'level 0 simple hazard'],
  ['hazards', 'drowning-pit.json', 'level 3 complex hazard'],
];

const upstream = ensureUpstream({ quiet: true });
const outDir = resolve(PROJECT_ROOT, 'tests/fixtures/upstream');
mkdirSync(outDir, { recursive: true });

const manifest = [];
for (const [pack, file, why] of FIXTURES) {
  const from = join(upstream, 'packs/pf2e', pack, file);
  const name = `${pack}__${file}`;
  copyFileSync(from, join(outDir, name));
  manifest.push({ file: name, pack, source: file, why });
  console.log(`  ${name}  (${why})`);
}

// The fixtures reference glossary strings and compendium entries that live
// elsewhere in the upstream repo. Commit just the slices they need so the test
// suite resolves markup exactly as the real build does, with no build step.
const { buildUuidIndex } = await import('./uuid-index.js');
const { loadGlossary } = await import('./glossary.js');
const { readFileSync } = await import('node:fs');

const fixtureText = manifest
  .map((m) => readFileSync(join(outDir, m.file), 'utf8'))
  .join('\n');

const glossary = loadGlossary(upstream);
const usedGlossary = {};
for (const key of new Set(fixtureText.match(/PF2E\.[A-Za-z0-9_.]+/g) ?? [])) {
  if (glossary.has(key)) usedGlossary[key] = glossary.get(key);
}
// Glossary strings contain their own references; pull those keys in too.
for (const value of Object.values({ ...usedGlossary })) {
  for (const key of value.match(/PF2E\.[A-Za-z0-9_.]+/g) ?? []) {
    if (glossary.has(key)) usedGlossary[key] = glossary.get(key);
  }
}

const { index } = buildUuidIndex(upstream);
const referenced = new Set([
  ...(fixtureText.match(/Compendium\.pf2e\.[A-Za-z0-9_-]+\.(?:Item|Actor)\.[^\]"]+/g) ?? []),
  ...Object.values(usedGlossary).flatMap(
    (v) => v.match(/Compendium\.pf2e\.[A-Za-z0-9_-]+\.(?:Item|Actor)\.[^\]"]+/g) ?? []
  ),
]);
const usedIndex = {};
for (const uuid of referenced) {
  const segments = uuid.split('.');
  const key = `${segments.at(-3)}:${segments.at(-1)}`;
  const hit = index.get(key) ?? index.get(`${segments.at(-3)}:${segments.at(-1).toLowerCase().replace(/[^a-z0-9]+/g, '-')}`);
  if (hit) usedIndex[key] = hit;
}

writeFileSync(
  resolve(PROJECT_ROOT, 'tests/fixtures/glossary.json'),
  `${JSON.stringify(usedGlossary, null, 2)}\n`
);
writeFileSync(
  resolve(PROJECT_ROOT, 'tests/fixtures/uuid-index.json'),
  `${JSON.stringify(usedIndex, null, 2)}\n`
);
console.log(`  ${Object.keys(usedGlossary).length} glossary strings, ${Object.keys(usedIndex).length} compendium refs`);

writeFileSync(
  resolve(PROJECT_ROOT, 'tests/fixtures/manifest.json'),
  `${JSON.stringify({ note: 'Generated by tools/build-data/make-fixtures.js. Do not hand-edit.', fixtures: manifest }, null, 2)}\n`
);
console.log(`\n${manifest.length} fixtures written to tests/fixtures/upstream/`);
